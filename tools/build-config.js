// Builds src/pkjs/config-page.js: the configuration page (config/config-page.html)
// with its CSS, scripts, images and fonts inlined so it can be opened from a data: URI and
// does not depend on any external server.
//
// usage: node tools/build-config.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p, enc) => fs.readFileSync(path.join(root, p), enc === undefined ? 'utf8' : enc);
const dataUri = (p, mime) => `data:${mime};base64,${read(p, null).toString('base64')}`;

let html = read('config/config-page.html');

// --- stylesheets -----------------------------------------------------------
html = html.replace(/<link href="(css\/[^"]+)"[^>]*>/g, (m, href) => {
  let css = read('config/' + href);
  // the heavy PF DIN webfont is dropped (falls back to PT Sans); the others are inlined
  css = css.replace(/@font-face\s*\{[^}]*PFDinDisplayPro-Light\.woff[^}]*\}/, '');
  css = css.replace(/PFDinDisplayProLightWebfont/g, 'PTSansRegularWebfont');
  css = css.replace(/url\("\.\.\/fonts\/([^"]+)"\)/g, (mm, f) =>
    `url("${dataUri('config/fonts/' + f, f.endsWith('.otf') ? 'font/otf' : 'font/woff')}")`);
  return `<style>\n${css}\n</style>`;
});

// --- scripts ---------------------------------------------------------------
html = html.replace(/<script type="text\/javascript" src="(js\/[^"]+)"><\/script>/g, (m, src) => {
  let js = read('config/' + src);
  if (src === 'js/pebble_config_scripts.js') {
    // take parameters injected by the phone-side code before looking at the URL
    js = js.replace('function getQueryParam(variable, defaultValue) {',
      'function getQueryParam(variable, defaultValue) {\n' +
      '\tif(window.__bcdParams && window.__bcdParams.hasOwnProperty(variable)) {\n' +
      '\t\treturn window.__bcdParams[variable];\n\t}');
  }
  return `<script>\n${js.replace(/<\/script>/g, '<\\/script>')}\n</script>`;
});

// --- images used by the live preview -----------------------------------------
html = html.replace(/img\/([A-Za-z0-9_]+\.png)/g, (m, f) => dataUri('config/img/' + f, 'image/png'));

// --- the page returns its result to the app directly (no save page on a server) ---
html = html.replace("getQueryParam('return_to', 'bcd_minimalist_slate_save.html?')",
                    "getQueryParam('return_to', 'pebblejs://close#')");

// --- branding ----------------------------------------------------------------
html = html.replace('BCD minimalist configuration', 'Binary Time configuration')
           .replace('>BCD minimalist</h1>', '>Binary Time</h1>');

// --- injection point for the parameters the phone-side code passes in ------------
const marker = '<!--BCD-PARAMS-->';
html = html.replace('<head>', '<head>' + marker);
if (!html.includes(marker)) throw new Error('could not place injection marker');

const out = `// GENERATED by tools/build-config.js - do not edit.\nmodule.exports = ${JSON.stringify(html)};\n`;
fs.writeFileSync(path.join(root, 'src/pkjs/config-page.js'), out);
console.log(`config page: ${(html.length / 1024).toFixed(0)} KB html, module ${(out.length / 1024).toFixed(0)} KB`);
